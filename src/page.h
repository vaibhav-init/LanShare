"<!doctype html><html><head><meta charset=utf-8>"
"<meta name=viewport content='width=device-width,initial-scale=1'>"
"<title>lanshare</title><style>"
":root{color-scheme:dark}"
"body{margin:0;font-family:system-ui,sans-serif;background:#111;color:#eee;"
"  display:flex;align-items:center;justify-content:center;min-height:100vh}"
".card{width:min(92vw,420px);text-align:center}"
"h1{font-size:1.1rem;font-weight:600;color:#9aa}"
"#drop{border:2px dashed #555;border-radius:16px;padding:38px 12px;"
"  font-size:1.05rem;cursor:pointer;transition:.2s}"
"#drop.hot{border-color:#7ab; background:#1a2a33}"
"input[type=file]{display:none}"
"#bar{height:8px;background:#283;border-radius:4px;overflow:hidden;margin-top:14px;display:none}"
"#fill{height:100%;width:0%;background:#5bd;transition:width .15s}"
"#pinrow{margin:18px 0}"
"#pin{font-size:1.6rem;letter-spacing:.4em;text-align:center;width:7em;"
"  padding:6px;border:1px solid #555;border-radius:10px;background:#000;"
"  color:#eee;outline:none}"
"#msg{margin-top:12px;min-height:1.4em;color:#9ab}"
"#drop.locked{opacity:.35;pointer-events:none}"
".err{color:#f76}.ok{color:#5d6}"
"</style></head><body><div class=card>"
"<h1>📡 lanshare — drop files to this laptop</h1>"
"<div id=pinrow><input id=pin maxlength=4 inputmode=numeric "
"  placeholder='· · · ·' autocomplete=off></div>"
"<div id=drop class=locked>enter the 4-digit code</div>"
"<input id=file type=file multiple>"
"<div id=bar><div id=fill></div></div>"
"<div id=msg></div>"
"</div>"
"<script>"
"const D=document.getElementById('drop'),F=document.getElementById('file'),"
"      P=document.getElementById('pin'),B=document.getElementById('bar'),"
"      L=document.getElementById('fill'),M=document.getElementById('msg');"
"let pin=new URLSearchParams(location.search).get('pin')"
"      ||localStorage.getItem('lsp')||'';"
"if(pin){P.value=pin;unlock();}"
"P.addEventListener('input',()=>{"
"  P.value=P.value.replace(/\\D/g,'').slice(0,4);"
"  if(P.value.length==4){localStorage.setItem('lsp',P.value);unlock();}});"
"function unlock(){pin=P.value;D.classList.remove('locked');"
"  D.textContent='drop files here — or tap';}"
"D.addEventListener('dragover',e=>{e.preventDefault();D.classList.add('hot');});"
"D.addEventListener('dragleave',()=>D.classList.remove('hot'));"
"D.addEventListener('drop',e=>{e.preventDefault();D.classList.remove('hot');"
"  send([...e.dataTransfer.files]);});"
"D.addEventListener('click',()=>F.click());"
"F.addEventListener('change',()=>send([...F.files]));"
"function send(files){let i=0;(function next(){"
"  if(i>=files.length){M.className='ok';M.textContent='all done ✓';"
"    L.style.width='0%';B.style.display='none';F.value='';return;}"
"  up(files[i++],next);})();}"
"function up(f,done){"
"  const x=new XMLHttpRequest(),name=f.name||'file';"
"  B.style.display='block';L.style.width='0%';M.className='';"
"  M.textContent=name+' — 0%';"
"  x.upload.onprogress=e=>{if(!e.lengthComputable)return;"
"    const p=Math.round(100*e.loaded/e.total);"
"    L.style.width=p+'%';M.textContent=name+' — '+p+'%';};"
"  x.open('POST','/upload');x.setRequestHeader('X-Pair',pin);"
"  const fd=new FormData();fd.append('file',f,f.name);"
"  x.onload=()=>{"
"    if(x.status==200){M.textContent=name+' ✓ saved';setTimeout(done,350);}"
"    else if(x.status==403){M.className='err';"
"      M.textContent='wrong or throttled code';localStorage.removeItem('lsp');}"
"    else if(x.status==413){M.className='err';M.textContent='file too big';}"
"    else{M.className='err';M.textContent=name+' failed';}"
"    if(x.status!=200)setTimeout(done,900);};"
"  x.onerror=()=>{M.className='err';M.textContent='connection lost';"
"    setTimeout(done,900);};"
"  x.send(fd);}"
"</script></body></html>";

#endif
